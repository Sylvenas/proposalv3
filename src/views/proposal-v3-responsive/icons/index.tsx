// Replacement icon set sourced from the Arctuition Design Library + audition
// section in the Interactive Proposal Figma file. One React component per
// icon. SVG path data is byte-equivalent to the Figma component (pixel-match).
//
// Two sizes are supported: 16x16 and 24x24 (per user requirement). Color is
// controlled via the `color` prop and applied through `currentColor` on the
// SVG fill, so paths inherit the desired color. Rotation and horizontal flip
// are applied via CSS transform on the SVG element.
//
// Components are named in PascalCase matching the Figma component (size
// suffix dropped — size is a prop). E.g. `chevron-thin-16x16` → `ChevronThin`.
// The audition section had a `paymemt-*` typo which is corrected here to
// `payment-*` per user direction (hyphen kept as the naming-convention
// separator). Components: `PaymentFailed`, `PaymentPending`, `PaymentSuccess`.
//
// Naming notes:
//  - `Date` → `DateIcon` (avoids collision with global Date)
// ─────────────────────────────────────────────────────────────────────────────

import type { CSSProperties, SVGProps } from 'react';

export type IconSize = 16 | 24;
export type IconRotate = 0 | 90 | 180 | 270;

export interface IconProps {
  /** Rendered display size in pixels. Only 16 and 24 are supported. */
  size?: IconSize;
  /** Clockwise rotation in degrees. Applied via CSS transform. */
  rotate?: IconRotate;
  /** Flip horizontally (applied AFTER rotation). */
  flipH?: boolean;
  /**
   * Override the icon color. Applied via the SVG's `fill` (which cascades to
   * paths whose own `fill` is removed). Defaults to the icon's natural color
   * (usually #262626; payment result icons keep their semantic colors).
   */
  color?: string;
  className?: string;
  style?: CSSProperties;
  /** Optional accessible label. When set, the icon is exposed to AT. */
  'aria-label'?: string;
  onClick?: SVGProps<SVGSVGElement>['onClick'];
}

// ── Internal helper: compute transform + base style ─────────────────────────
function svgStyle(props: IconProps): CSSProperties {
  const transforms: string[] = [];
  if (props.rotate) transforms.push(`rotate(${props.rotate}deg)`);
  if (props.flipH) transforms.push('scaleX(-1)');
  return {
    flexShrink: 0,
    display: 'inline-block',
    transform: transforms.length ? transforms.join(' ') : undefined,
    transformOrigin: 'center',
    ...props.style,
  };
}

// Common attrs for every <svg>.
function commonSvgAttrs(size: IconSize, color: string, props: IconProps) {
  const ariaLabel = props['aria-label'];
  return {
    width: size,
    height: size,
    fill: color,
    xmlns: 'http://www.w3.org/2000/svg' as const,
    'aria-hidden': ariaLabel ? undefined : (true as const),
    'aria-label': ariaLabel,
    role: ariaLabel ? 'img' : undefined,
    className: props.className,
    style: svgStyle(props),
    onClick: props.onClick,
  };
}

